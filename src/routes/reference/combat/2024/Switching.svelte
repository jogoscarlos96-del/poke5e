<p>These Kornia rules modify switching in sanctioned Trainer battles. Switching never creates a free Pokémon command unless a feature specifically says it does.</p>

<h3>Voluntary Switching</h3>
<p>As an <strong>Action</strong>, a Trainer may recall one or two active Pokémon within line of sight and up to 60 feet away, then release the same number of eligible Pokémon within line of sight and up to 15 feet away.</p>
<p>A Pokémon voluntarily switched in during an ongoing round may immediately <strong>move up to its Speed</strong>. It cannot take an Action, receive a Bonus Action Move command, or use its Reaction during that round.</p>
<p>This movement counts as that Pokémon's participation for the round. If an initiative position associated with that Pokémon occurs later in the same round, it does not participate again.</p>
<p>The Trainer's Action was spent on the Switch, so no normal Action command is created for the incoming Pokémon.</p>

<h3>Forced Replacement</h3>
<p>When one or more of a Trainer's active Pokémon faint, the Trainer may immediately replace them by using the <strong>Trainer's Reaction</strong>. A single Forced Replacement may replace every Pokémon belonging to that Trainer that fainted during the same <dfn>Replacement Window</dfn>.</p>
<p>A <strong>Replacement Window</strong> is one continuous event or effect that causes one or more of that Trainer's active Pokémon to faint before combat continues. Pokémon that faint later from a separate attack or effect create a new Replacement Window.</p>
<p>If the Trainer's Reaction has already been spent, the replacement still occurs and the Trainer gains <strong>Reaction Debt</strong>.</p>

<h3>Reaction Debt</h3>
<p>When a Trainer with Reaction Debt would next regain their Reaction, they do not regain it. Reaction Debt is cleared instead. At the following normal Reaction refresh, the Trainer regains their Reaction normally.</p>
<p>Reaction Debt does <strong>not</strong> stack. A Trainer can never owe more than one future Reaction, even if additional Forced Replacements occur before the debt is cleared.</p>

<h3>Forced Replacement and Action Economy</h3>
<p>Forced Replacement only puts the new Pokémon onto the battlefield. It does <strong>not</strong> itself grant movement, an Action, a Bonus Action, or an Action command.</p>
<p>After entering, the replacement may only use normal movement and commands that the Trainer still has a legitimate opportunity to use. For example:</p>
<ul>
	<li>If the replacement enters before the Trainer's turn, it may participate normally when that turn occurs.</li>
	<li>If it enters during the Trainer's turn while the Trainer still has an Action or Bonus Action they could legally use, those remaining resources may be used normally.</li>
	<li>If the relevant Trainer Action or Bonus Action has already been spent, the replacement does not gain another one and must wait for the next normal opportunity.</li>
</ul>
<p>A normal Pokémon entering through Forced Replacement has its own Reaction, but cannot use that Reaction until after its first normal participation following the replacement.</p>

<h3>Double Battles</h3>
<ul>
	<li>One voluntary Switch Action may replace up to two active Pokémon. Each incoming Pokémon may move up to its own Speed, but neither gains an Action, Bonus Action Move command, or Reaction during that round.</li>
	<li>If multiple Pokémon faint during the same Replacement Window, one Trainer Reaction replaces all of them.</li>
	<li>If Pokémon faint during separate Replacement Windows, later replacements still occur even if the Trainer's Reaction is already spent; Reaction Debt applies as normal.</li>
</ul>

<h3>No Double Participation</h3>
<p>A Pokémon cannot participate twice in the same round because it switched in.</p>
<ul>
	<li><strong>Voluntary Switch:</strong> its switch-in movement is its participation for that round.</li>
	<li><strong>Forced Replacement:</strong> the replacement itself is not participation. The Pokémon participates when the Trainer next has a legitimate normal command opportunity.</li>
</ul>

<h3>Start-of-Round Replacement</h3>
<p>If a Trainer begins a new round without an active Pokémon and must send out a replacement, treat this as a Forced Replacement. The Pokémon may participate normally when the Trainer has their normal turn that round.</p>

<h3>Reactions Are Separate</h3>
<p>The Trainer and every Pokémon have separate Reactions. A fainted Pokémon having spent its Reaction does not affect the Trainer's Reaction or the replacement Pokémon's Reaction.</p>

<h3>Recall Effects</h3>
<p>Returning a Pokémon to its Pokéball does not provoke an attack of opportunity. Concentration ends, and move- or item-based buffs and debuffs that normally end on recall are removed. Persistent status conditions remain unless their own rules say otherwise; Asleep and Confusion pause their round duration, and Poison and Burn do not deal damage while the Pokémon is inside its Pokéball.</p>

